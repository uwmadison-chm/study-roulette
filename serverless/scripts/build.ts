/**
 * Validate the routing config and bake it into the bundles.
 *
 *   node scripts/build.ts [--config studies.json] [--generate-only]
 *
 * Any config error fails the build, so an invalid config never deploys.
 * Outputs:
 *   dist/worker/worker.mjs     Cloudflare Workers module
 *   dist/lambda/index.mjs      AWS Lambda handler (index.handler)
 *   dist/node/server.mjs       Plain Node server
 *   dist/configurator/         Static configurator page
 */
import { execSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import * as esbuild from "esbuild";
import { validateConfig } from "../src/core/config.ts";
import { sha256Hex } from "../src/store/sigv4.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { values: args } = parseArgs({
  options: {
    config: { type: "string", default: "studies.json" },
    "generate-only": { type: "boolean", default: false },
  },
});

const configPath = join(root, args.config!);
let raw: string;
try {
  raw = readFileSync(configPath, "utf8");
} catch {
  console.error(
    `Cannot read ${args.config}. Create it with the configurator, or copy studies.example.json.`,
  );
  process.exit(1);
}

let data: unknown;
try {
  data = JSON.parse(raw);
} catch (e) {
  console.error(`${args.config} is not valid JSON: ${(e as Error).message}`);
  process.exit(1);
}

const { config, errors } = validateConfig(data);
if (!config) {
  console.error(`${args.config} is invalid:\n${errors.map((e) => `  - ${e}`).join("\n")}`);
  process.exit(1);
}

let gitSha = "nogit";
try {
  gitSha = execSync("git rev-parse --short HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
    .toString()
    .trim();
} catch {
  // not a git checkout; fine
}
const configHash = (await sha256Hex(JSON.stringify(config))).slice(0, 8);
const buildId = `${gitSha}-${configHash}`;

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/config.ts"),
  `// Generated by scripts/build.ts from ${args.config}. Do not edit.\n` +
    `import type { Config } from "../core/config.ts";\n\n` +
    `export const buildId = ${JSON.stringify(buildId)};\n\n` +
    `export const config: Config = ${JSON.stringify(config, null, 2)};\n`,
);

if (args["generate-only"]) process.exit(0);

const common: esbuild.BuildOptions = {
  bundle: true,
  format: "esm",
  minify: false,
  sourcemap: false,
  legalComments: "none",
  logLevel: "warning",
};

await Promise.all([
  esbuild.build({
    ...common,
    entryPoints: [join(root, "src/entry/worker.ts")],
    outfile: join(root, "dist/worker/worker.mjs"),
    platform: "neutral",
    target: "es2022",
  }),
  esbuild.build({
    ...common,
    entryPoints: [join(root, "src/entry/lambda.ts")],
    outfile: join(root, "dist/lambda/index.mjs"),
    platform: "node",
    target: "node22",
  }),
  esbuild.build({
    ...common,
    entryPoints: [join(root, "src/entry/node.ts")],
    outfile: join(root, "dist/node/server.mjs"),
    platform: "node",
    target: "node22",
  }),
  esbuild.build({
    ...common,
    format: "iife",
    entryPoints: [join(root, "configurator/app.ts")],
    outfile: join(root, "dist/configurator/app.js"),
    platform: "browser",
    target: "es2022",
  }),
]);
copyFileSync(join(root, "configurator/index.html"), join(root, "dist/configurator/index.html"));

console.log(`Built ${buildId}: ${config.studies.length} studies + fallback`);
